import Holidays from "date-holidays";
import {
  writeFileSync,
  mkdirSync,
  rmSync,
  existsSync,
  readFileSync,
} from "node:fs";

const thisYear = new Date().getFullYear();
const YEARS = [thisYear, thisYear + 1];

type Row = { date: string; name: string };

const base = new Holidays();
const countries = base.getCountries("en") as Record<string, string>;

const out: Record<string, { name: string; holidays: Row[] }> = {};
let empty = 0;

for (const [code, name] of Object.entries(countries)) {
  const hd = new Holidays(code);
  const rows: Row[] = [];

  for (const year of YEARS) {
    for (const h of hd.getHolidays(year, "en")) {
      if (h.type !== "public") continue; // official public holidays only
      rows.push({ date: h.date.slice(0, 10), name: h.name });
    }
  }

  // remove duplicates (same date + name) and sort by date
  const seen = new Set<string>();
  const unique = rows
    .filter((r) => {
      const k = `${r.date}|${r.name}`;
      if (seen.has(k)) return false;
      seen.add(k);
      return true;
    })
    .sort((a, b) => a.date.localeCompare(b.date));

  if (unique.length === 0) empty++;
  out[code] = { name, holidays: unique };
}
// Keep the old timestamp when nothing changed, so git sees no diff
const next = { years: YEARS, countries: out };
let generatedAt = new Date().toISOString();
if (existsSync("data/holidays.json")) {
  const prev = JSON.parse(readFileSync("data/holidays.json", "utf8"));
  if (
    JSON.stringify({ years: prev.years, countries: prev.countries }) ===
    JSON.stringify(next)
  ) {
    generatedAt = prev.generatedAt;
  }
}

mkdirSync("data", { recursive: true });
writeFileSync("data/holidays.json", JSON.stringify({ generatedAt, ...next }));
mkdirSync("data", { recursive: true });
writeFileSync(
  "data/holidays.json",
  JSON.stringify({
    generatedAt: new Date().toISOString(),
    years: YEARS,
    countries: out,
  }),
);

// one tiny entry file per country, for "world-holidays/country/XX"
rmSync("src/countries", { recursive: true, force: true });
mkdirSync("src/countries", { recursive: true });
for (const [code, c] of Object.entries(out)) {
  writeFileSync(
    `src/countries/${code}.ts`,
    `// generated by scripts/generate.ts, do not edit
import { createCountry } from "../country";

export const country = createCountry(${JSON.stringify(code)}, ${JSON.stringify(c.name)}, ${JSON.stringify(c.holidays)}, ${JSON.stringify(YEARS)});
export default country;
`,
  );
}

console.log(
  `Done: ${Object.keys(out).length} countries, years ${YEARS.join(", ")}, ${empty} with no public holidays`,
);
